export type CollegeKey = "engineering" | "nursing" | "pharmacy" | "emerging_sciences";

export type AdminRole =
  | "SUPER_ADMIN"
  | "ADMISSION_ENGINEERING"
  | "ADMISSION_NURSING"
  | "ADMISSION_PHARMACY"
  | "ADMISSION_EMERGING";

export type DegreeLevel = "UG" | "PG" | "Ph.D.";
export type DegreeCode = "1" | "2" | "3";

export type AdmissionQuota =
  | "ENTRANCE_QUOTA"
  | "MANAGEMENT_QUOTA";

export function formatQuota(quota?: string): string {
  if (!quota) return "";
  if (quota === "ENTRANCE_QUOTA") return "Entrance Quota";
  if (quota === "MANAGEMENT_QUOTA" || quota === "MANAGEMENT") return "Management Quota";
  return quota.replace(/_/g, " ");
}

export type AdmissionStatus =
  | "DRAFT"
  | "PENDING_VERIFICATION"
  | "DOCS_VERIFIED"
  | "ADMITTED"
  | "REJECTED";

export interface DocumentAttachment {
  fileName: string;
  fileSize: number; // in bytes
  fileType: string; // "application/pdf", "image/png", "image/jpeg"
  dataUrl: string; // Base64 Data URL for real preview / download
  uploadedAt: string;
}

export interface AadharFeedData {
  aadharNumber: string; // 12-digit string
  isVerified: boolean;
  verifiedBy?: string;
  verifiedAt?: string;
  document?: DocumentAttachment;
  documentName?: string;
}

